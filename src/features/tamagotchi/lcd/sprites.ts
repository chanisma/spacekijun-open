/**
 * 다마고찌 도트 그림 — 32×16 LCD 에 찍히는 원본 스프라이트.
 *
 * 원작 P1 의 문법(검은 덩어리 몸 + 꺼진 점으로 낸 눈, 두 장 번갈아 0.5초 걷기)을 따르되
 * **캐릭터는 이 앱의 것**이다 — 별빛 아카데미의 펫이라 머리에 별이 자라는 한 줄기로 그렸다.
 * 반다이 캐릭터를 옮기지 않는다.
 *
 * 형식: '#' = 켜진 점, '.' = 꺼진 점. 행 길이는 같아야 한다(회귀가 검사한다).
 */

export type Sprite = readonly string[];

export interface SpriteFrames {
  /** 걷기·숨쉬기 두 장 */
  idle: readonly [Sprite, Sprite];
  /** 입 벌림 (먹기) */
  eat: Sprite;
  /** 기쁨 */
  happy: Sprite;
  /** 고개 젓기·싫음 */
  no: Sprite;
  /** 잠 */
  sleep: Sprite;
}

