/** 한국 날짜(YYYY-MM-DD) → 그날의 질문 */
export function questionOf(kstDate: string): string {
  const day = Math.floor(Date.parse(`${kstDate}T00:00:00Z`) / 86_400_000);
  const n = DAILY_QUESTIONS.length;
  return DAILY_QUESTIONS[((day % n) + n) % n];
}
