// 프롬프트 방언(모델별)·작성 모드(엄격/생성) 단일 출처.
//
// **왜 별도 모듈인가**: 이 두 축은 프롬프트를 만드는 `llm.ts`와 모델을 고르는
// `specFillService.ts`가 **함께** 알아야 하는데, 서비스가 llm을 import하는 방향이라
// 반대로 두면 순환이 된다. 값만 담은 이 모듈을 양쪽이 참조한다.

/**
 * 프롬프트 방언 — 어떤 모델에게 말하고 있는가.
 *
 * **문자열이 아니라 "모델을 받아 문자열을 만드는 함수"로 프롬프트를 넘기는 이유**가
 * 여기 있다. 문서 생성 경로는 luna 실패 시 solar로 넘어가는데, 프롬프트를 미리 문자열로
 * 굳혀 두면 **luna용 지시문이 그대로 solar에 실린다**. 방언을 시도 시점에 해석해야
 * fallback이 자기 모델에 맞는 프롬프트를 받는다.
 */
export type PromptDialect = 'luna' | 'solar';

/** 프롬프트 조각 — 문자열(방언 무관) 또는 방언을 받아 만드는 함수 */
export type PromptText = string | ((dialect: PromptDialect) => string);

/** 시도 시점에 방언을 적용해 최종 문자열을 얻는다 */
export function resolvePrompt(text: PromptText, dialect: PromptDialect): string {
  return typeof text === 'function' ? text(dialect) : text;
}

/**
 * 작성 모드(2026-09-02 사용자 결정) — **기본은 `strict`**.
 *
 * - `strict`: 자료(knowledge·사용자 설명)에 없는 사실을 만들지 않는다. 학교 공문서는
 *   지어낸 값이 그대로 발송될 수 있어 이쪽이 기본이다.
 * - `generate`: 자료에 없어도 문서 목적에 맞게 적극적으로 초안을 쓴다. 사용자가
 *   "빈 칸을 채워 달라"고 명시적으로 고른 경우.
 *
 * **두 모드 모두 `_fabricated`에 지어낸 키를 남긴다** — generate에서 표식까지 없애면
 * 검토자가 어디를 확인해야 할지 알 수 없다. 모드는 "만들지 여부"를 정하지
 * "숨길지 여부"를 정하지 않는다.
 */
export type SpecFillMode = 'strict' | 'generate';

export const DEFAULT_SPEC_FILL_MODE: SpecFillMode = 'strict';

/**
 * 사실 생성 규칙 한 줄 — 프롬프트 5곳이 공유한다.
 *
 * 예전엔 `'사실을 지어내지 않는다'`가 세 프롬프트에 각각 복붙돼 있어, 모드를 도입하려면
 * 세 군데를 따로 고쳐야 했고 문구가 서로 어긋나 있었다.
 */
export function fabricationRule(mode: SpecFillMode): string {
  return mode === 'generate'
    ? '자료에 없는 내용도 문서 유형과 사용자 설명에 맞게 **적극적으로 작성**한다 — 빈 칸을 남기지 말 것. 단, 자료에서 확인되지 않아 네가 만든 값의 키 이름을 최상위 "_fabricated" 문자열 배열에 빠짐없이 나열한다(사람이 검토한다).'
    // **빈 칸으로 두는 탈출구가 반드시 있어야 한다**(2026-09-02).
    //
    // 종전 엄격 규칙은 ①모든 키를 채워라 ②지어내지 마라 ③예시를 복사하지 마라를 동시에
    // 요구했다. 사용자 설명이 얇고 knowledge가 비면 **셋을 동시에 만족할 수 없고**, 모델은
    // 가장 싼 위반을 고른다 — 눈앞에 있고 바로 이 문서에서 나와 그럴듯한 **양식 예시의 내용**을
    // 가져다 쓰는 것이다("형식만 참고" 설계가 깨지던 실제 경로).
    //
    // 그래서 "근거가 없으면 비워라"를 명시적으로 허용한다. 빈 칸은 `validatePlan`이 오류로
    // 잡지 않고(스칼라 빈 문자열은 통과), 계획 검토의 실행 게이트(`missingPlanInputs`)가
    // 사람에게 채우라고 요구하므로 **빈 채로 문서가 나가지 않는다** — 탈출구가 안전한 이유다.
    : '사실을 지어내지 않는다. 자료에서 확인되지 않는 값은 **빈 문자열로 두고** 그 키 이름을 최상위 "_fabricated" 배열에 나열한다 — 사람이 계획 검토에서 채운다. 빈 칸을 남기는 것이 양식에 원래 적혀 있던 다른 문서의 내용을 가져다 쓰는 것보다 **항상 낫다**.';
}

/** 서술(prose) 계열 프롬프트용 — 배열 키가 없는 문맥이라 표식 문구를 뺀 형태 */
export function fabricationRuleProse(mode: SpecFillMode): string {
  return mode === 'generate'
    ? '자료에 없는 내용도 문서 유형·지침에 맞게 적극적으로 작성한다 — 빈 칸이나 "(내용 없음)" 같은 회피 표현을 쓰지 말 것. 확인되지 않은 구체 수치·고유명사는 피하고 일반적 서술로 쓴다.'
    : '자료에 없는 사실을 지어내지 않는다 — 확인되지 않은 수치·날짜·고유명사를 쓰지 말고, 주어진 자료 범위에서 쓴다.';
}

/**
 * 방언별 출력 형식 지시.
 *
 * **luna**: JSON 출력을 코드펜스 없이 곧장 내는 편이고 지시가 길면 앞부분에 끌린다 —
 * 출력 계약을 첫 줄에 두고 금지사항을 짧게 못박는다.
 * **solar-pro3**: 추론형이라 서두 지시가 길어도 잘 따르지만, 설명 문장을 덧붙이는
 * 경향이 있어 "설명 금지"를 명시적으로 반복해야 한다.
 *
 * 두 문장 모두 같은 계약(JSON 하나만)을 말하며 **의미가 갈리지 않게** 유지할 것 —
 * 방언은 표현의 문제이지 계약의 문제가 아니다.
 */
export function outputContract(dialect: PromptDialect, shape: string): string {
  return dialect === 'luna'
    ? `출력은 ${shape} 하나뿐이다. 코드펜스·머리말·설명 문장을 붙이지 않는다.`
    : `${shape} 하나만 출력한다. 설명 문장·사고 과정·머리말을 절대 덧붙이지 않는다. 코드펜스로 감싸도 된다.`;
}
