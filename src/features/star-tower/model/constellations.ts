/**
 * 등성 별자리(2026-10-23 사용자 요청 «등성 시스템으로 길어진 플레이에 맞게 도감 늘리기») — 탑을 완성할 때마다 하나씩.
 * 층이 아니라 «완성한 탑 수»로 열리므로 새 탑을 1층부터 다시 쌓아도 닫히지 않는다.
 * 자리 = 가운데 줄(x 56~96) — 층 별자리가 왼쪽(x ≤ 46)·오른쪽(x ≥ 104) 줄을 쓰므로 겹치지 않는다(회귀가 검사).
 */
