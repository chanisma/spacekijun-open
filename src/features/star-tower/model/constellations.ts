export function unlockedRankConstellations(towers: number): RankConstellation[] {
  return RANK_CONSTELLATIONS.filter((c) => towers >= c.towersAt);
}

export function unlockedConstellations(builtCount: number): Constellation[] {
  return CONSTELLATIONS.filter((c) => builtCount >= c.unlockAt);
}

/** 다음에 열릴 별자리 — 없으면 null */
export function nextConstellation(builtCount: number): Constellation | null {
  return CONSTELLATIONS.find((c) => builtCount < c.unlockAt) ?? null;
}
