/**
 * 별자리 — 이 물에 잠긴 세계의 사람들이 붙인 이름. 층을 2개 쌓을 때마다 하나씩 드러난다.
 *
 * 별자리는 하늘의 «높이»에 놓인다(altitude = 수면에서 위로 잰 세계 픽셀). 탑이 그 높이에 가까워질 때
 * 열리도록 놓았으므로, 새 별자리는 대개 탑 꼭대기 바로 위 하늘에 나타난다 — "높이 쌓을수록 별이 보인다"를 말 그대로.
 */

export interface Constellation {
  key: string;
  name: string;
  story: string;
  /** 쌓은 층 수가 이만큼이면 열린다 */
  unlockAt: number;
  /** 하늘에서의 자리 — x 는 화면 폭(160) 기준, altitude 는 수면 위 높이 */
  x: number;
  altitude: number;
  /** 별 좌표(자리 기준 0~40 × 0~30) · 밝기(1~3) */
  stars: [number, number, number][];
  lines: [number, number][];
}

