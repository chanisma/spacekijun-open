/**
 * 라벨 앞에 달라붙은 부가조건 꼬리를 떼어 낸다.
 *
 * `splitCsatBlocks` 가 앞 블록의 부가조건 문장을 라벨에 흡수하는 경우가 있다
 * (`등급 상향 의예`, `약학은 수(미/기)와 과 필수 반영 간호`). 이때 **마지막 토큰이
 * 사전에 있으면** 그것을 라벨로 본다. 사전에 없으면 그대로 두어 결국 매칭에 실패하고
 * 보류된다 — 추측해서 잘라내지 않는다.
 */
export function normalizeCsatLabel(label: string): string {
  const t = (label ?? '').trim();
  if (!t) return '';
  if (CSAT_LABEL_TERMS[t] || CSAT_SERIES_LABELS[t]) return t;
  const parts = t.split(/\s+/);
  if (parts.length > 1) {
    const last = parts[parts.length - 1];
    if (CSAT_LABEL_TERMS[last] || CSAT_SERIES_LABELS[last]) return last;
  }
  return t;
}

/** 라벨 목록 → 매칭어 (사전에 없는 라벨은 조용히 빠진다) */
export function termsForLabels(labels: string[]): string[] {
  const out: string[] = [];
  for (const raw of labels) {
    const key = normalizeCsatLabel(raw);
    for (const term of CSAT_LABEL_TERMS[key] ?? []) {
      if (!out.includes(term)) out.push(term);
    }
  }
  return out;
}

/** 라벨 목록 → 계열 (여러 계열이 섞이면 판단 보류로 null) */
export function seriesForLabels(labels: string[]): '인문' | '자연' | null {
  const found = new Set<'인문' | '자연'>();
  for (const raw of labels) {
    const s = CSAT_SERIES_LABELS[normalizeCsatLabel(raw)];
    if (s) found.add(s);
  }
  return found.size === 1 ? [...found][0] : null;
}

/** 사전이 이 라벨 묶음을 해석할 수 있는가 (하나도 못 풀면 그 블록은 건너뛴다) */
export function canResolveLabels(labels: string[]): boolean {
  return termsForLabels(labels).length > 0 || seriesForLabels(labels) !== null;
}
