// ========================================
// 부서명 축약 (모바일 북마크 탭용)
// 풀네임 대신 구분 가능한 핵심 표현만 남긴다.
// department 테이블은 admin이 자유롭게 추가할 수 있으므로
// 알려진 부서는 명시 매핑, 나머지는 접미사(부/과) 제거 폴백.
// ========================================

const SHORT_NAME_MAP: Record<string, string> = {
  // 행정 부서 — 핵심 토큰만 ('부' 접미사도 제거)
  '교무운영부': '교무',
  '교육과정부': '과정',
  '교육연구부': '연구',
  // '정보'로 줄이면 정보과(폴백 → '정보')와 탭 이름이 겹친다
  '정보화부': '정보화',
  '신학년부': '신학년',
  '어문학부': '어문',
  '수리과학부': '수리',
  '예능사회부': '예능',
  '인성인권부': '인권',
  '생활선교부': '선교',
  '진로상담부': '진로',
  // 교과 — 긴 이름만 별도 축약 (짧은 교과는 폴백으로 처리)
  '제2외국어과': '제2외',
  '제3외국어과': '제3외',
  '기술가정과': '기가',
};

/**
 * 부서 풀네임 → 모바일용 축약명.
 * - 매핑에 있으면 그대로 사용
 * - 'N학년부' → 'N학년'
 * - 3자 이상이고 '부'/'과'로 끝나면 접미사 제거 (국어과→국어, 수학과→수학)
 * - 그 외(축약 불가/이미 짧음)는 풀네임 유지
 */
export function shortDeptName(name: string): string {
  const mapped = SHORT_NAME_MAP[name];
  if (mapped) return mapped;

  if (/^\d학년부$/.test(name)) return name.slice(0, -1);
  if (name.length >= 3 && /[부과]$/.test(name)) return name.slice(0, -1);
  return name;
}
