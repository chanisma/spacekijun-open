/**
 * 실행 단계 제목의 «중복 번호» 제거 — 표시 단계에서만 (2026-09-23).
 *
 * 화면은 단계마다 **동그라미 번호**(`index + 1`)를 이미 그린다. 그런데 LLM 이 제목에도
 * `1. 개념을 조작적으로 정의하고 설문 설계하기` 처럼 번호를 붙여 보낼 때가 있어
 * `① 1. 개념을…` 으로 두 번 매겨진 것처럼 보인다.
 *
 * ── 왜 프롬프트 규칙이 아니라 표시 단계인가 ────────────────────────────────
 * ①**빈도가 확률이다.** 라이브 실측(2026-09-23, `student_inquiry_designs` 의 plan_steps
 *   53건): 번호가 붙은 것은 **12건(23%)**. 모델은 이미 대부분 지키고 있고, 지시를 더해도
 *   0% 로 내려가지 않는다 — 가끔 나타나는 결함은 가끔 나타나는 채로 남는다.
 * ②**이미 저장된 12건은 프롬프트로 고쳐지지 않는다.** 표시 단계에서 다루면 과거 설계도
 *   함께 낫는다(마이그레이션 없이).
 * ③**되돌릴 수 있다.** 저장할 때 지우면 원문이 사라져 규칙이 틀렸을 때 복구할 수 없다.
 *   화면은 저장된 값에서 매번 유도하므로 규칙을 고치면 즉시 되돌아온다.
 *
 * ── 안전장치: «번호가 제 자리와 같을 때만» 지운다 ──────────────────────────
 * 실측 12건은 **전부 제 위치와 같은 번호**였다(1번 단계에 `1.`). 이 조건을 걸면
 * `2026. 1학기 자료 수집` 같은 제목이 잘려 나가는 사고가 **구조적으로 불가능**해진다
 * (2026 은 어떤 단계 번호와도 같을 수 없다). 번호가 자리와 어긋나면 손대지 않는다 —
 * 그건 모델이 순서를 잘못 붙였다는 뜻이고, 조용히 지우면 그 사실이 감춰진다.
 *
 * ⚠️ **React key 로 쓰지 말 것.** 두 단계가 `1. 자료 수집` · `2. 자료 수집` 이면 번호를
 * 뗀 값이 서로 같아진다. 호출부는 지금처럼 원문(`step.title`)을 key 로 쓴다.
 */

/**
 * 제목 맨 앞의 순번 표기. `(1)` 은 괄호가 경계를 만들어 주므로 구분자가 필요 없고,
 * 나머지는 **구분자를 반드시 요구**한다 — 없으면 `3 학년 대상 설문` 의 `3` 까지 번호로
 * 읽힌다. 자릿수를 2 로 묶은 것도 같은 이유(연도·수치가 걸리지 않게).
 */
const LEADING_ORDINAL = /^\s*(?:\((\d{1,2})\)|(\d{1,2})\s*(?:단계)?\s*[.)．。:：\-–—])\s*/;

/**
 * 화면에 그릴 단계 제목. `index` 는 **0-based**(화면의 동그라미는 `index + 1`).
 *
 * 번호를 떼지 않는 경우: 순번 표기가 없을 때 · 번호가 제 자리와 다를 때 ·
 * 번호를 떼면 제목이 비어 버릴 때(`1.` 만 있는 제목).
 */
export function planStepTitle(title: string | null | undefined, index: number): string {
  if (typeof title !== 'string') return '';
  const trimmed = title.trim();

  const match = LEADING_ORDINAL.exec(trimmed);
  if (!match) return trimmed;

  const ordinal = Number(match[1] ?? match[2]);
  if (ordinal !== index + 1) return trimmed;

  const stripped = trimmed.slice(match[0].length).trim();
  return stripped || trimmed;
}
