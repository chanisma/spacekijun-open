/**
 * Subject Combination Configuration Component
 * 과목 조합 매칭 알고리즘 설정 UI
 */

import React, { useState, useMemo } from 'react';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Badge } from '@/components/ui/badge';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@/components/ui/select';
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogTrigger,
  DialogFooter,
} from '@/components/ui/dialog';
import { Checkbox } from '@/components/ui/checkbox';
import { ScrollArea } from '@/components/ui/scroll-area';
import { X, Plus, Users, Target, Beaker, BookOpen, Palette } from 'lucide-react';
import { useClassAssignmentContext } from '../../context/ClassAssignmentContext';
import { useCourseIntegration } from '../../hooks/useCourseIntegration';
import type { SubjectCombination } from '../../utils/algorithms/subjectBased';
import { matchesSubjectCombination, getStudentSubjects } from '../../utils/algorithms/subjectBased';

interface SubjectCombinationConfigProps {
  combinations: SubjectCombination[];
  onCombinationsChange: (combinations: SubjectCombination[]) => void;
}

// 자주 사용되는 과목 조합 프리셋
const COMBINATION_PRESETS: Omit<SubjectCombination, 'id' | 'targetClassNum'>[] = [
  {
    name: '물리+화학',
    requiredSubjects: ['물리학', '화학'],
    priority: 10,
  },
  {
    name: '생명+지구과학',
    requiredSubjects: ['생명과학', '지구과학'],
    priority: 10,
  },
  {
    name: '물리+화학+생명',
    requiredSubjects: ['물리학', '화학', '생명과학'],
    priority: 15,
  },
  {
    name: '정치와법+경제',
    requiredSubjects: ['정치와법', '경제'],
    priority: 10,
  },
  {
    name: '세계지리+세계사',
    requiredSubjects: ['세계지리', '세계사'],
    priority: 10,
  },
  {
    name: '사회문화+생활과윤리',
    requiredSubjects: ['사회·문화', '생활과 윤리'],
    priority: 10,
  },
  {
    name: '미술+음악',
    requiredSubjects: ['미술', '음악'],
    optionalSubjects: ['체육', '연극'],
    minOptionalCount: 0,
    priority: 5,
  },
];

export const SubjectCombinationConfig: React.FC<SubjectCombinationConfigProps> = ({
  combinations,
  onCombinationsChange,
}) => {
  const { sourceStudents, config } = useClassAssignmentContext();
  const { getAvailableSubjects } = useCourseIntegration();

  const [isDialogOpen, setIsDialogOpen] = useState(false);
  const [editingCombination, setEditingCombination] = useState<SubjectCombination | null>(null);

  // 새 조합 폼 상태
  const [name, setName] = useState('');
  const [selectedRequired, setSelectedRequired] = useState<string[]>([]);
  const [selectedOptional, setSelectedOptional] = useState<string[]>([]);
  const [targetClass, setTargetClass] = useState<number | null>(null);
  const [targetClassCount, setTargetClassCount] = useState<number | null>(null);
  const [priority, setPriority] = useState(10);

  // 사용 가능한 과목 목록
  const availableSubjects = useMemo(() => {
    const subjects = getAvailableSubjects();
    if (subjects.length > 0) return subjects;

    // 과목 데이터가 없으면 학생 데이터에서 추출
    const subjectSet = new Set<string>();
    sourceStudents.forEach(s => {
      getStudentSubjects(s).forEach(subj => subjectSet.add(subj));
    });
    return Array.from(subjectSet).sort();
  }, [getAvailableSubjects, sourceStudents]);

  // 각 조합의 해당 학생 수 계산
  const getMatchingStudentCount = (combination: SubjectCombination): number => {
    return sourceStudents.filter(s => matchesSubjectCombination(s, combination)).length;
  };

  // 현재 선택 중인 과목 조합의 미리보기 인원수 (실시간)
  const previewMatchCount = useMemo(() => {
    if (selectedRequired.length === 0) return 0;

    const previewCombination: SubjectCombination = {
      id: 'preview',
      name: 'preview',
      requiredSubjects: selectedRequired,
      optionalSubjects: selectedOptional.length > 0 ? selectedOptional : undefined,
      minOptionalCount: selectedOptional.length > 0 ? 1 : undefined,
    };

    return sourceStudents.filter(s => matchesSubjectCombination(s, previewCombination)).length;
  }, [selectedRequired, selectedOptional, sourceStudents]);

  // 자동 이름 생성 (선택한 과목 기반)
  const autoGeneratedName = useMemo(() => {
    if (selectedRequired.length === 0) return '';

    // 과목명 줄이기 (예: 물리학Ⅰ → 물리, 생명과학Ⅱ → 생명)
    const shortenSubject = (subject: string): string => {
      return subject
        .replace(/Ⅰ|Ⅱ|I|II|1|2/g, '')
        .replace(/학$/, '')
        .replace(/과학$/, '')
        .trim();
    };

    const shortNames = selectedRequired.map(shortenSubject);
    return shortNames.join('+');
  }, [selectedRequired]);

  // 조합 아이콘
  const getCombinationIcon = (name: string) => {
    if (name.includes('물리') || name.includes('화학') || name.includes('생명') || name.includes('지구')) {
      return <Beaker className="h-4 w-4 text-blue-500" />;
    }
    if (name.includes('정치') || name.includes('경제') || name.includes('사회') || name.includes('지리') || name.includes('역사')) {
      return <BookOpen className="h-4 w-4 text-green-500" />;
    }
    if (name.includes('미술') || name.includes('음악') || name.includes('체육')) {
      return <Palette className="h-4 w-4 text-purple-500" />;
    }
    return <Target className="h-4 w-4 text-gray-500" />;
  };

  // 폼 초기화
  const resetForm = () => {
    setName('');
    setSelectedRequired([]);
    setSelectedOptional([]);
    setTargetClass(null);
    setTargetClassCount(null);
    setPriority(10);
    setEditingCombination(null);
  };

  // 프리셋 적용
  const applyPreset = (preset: Omit<SubjectCombination, 'id' | 'targetClassNum'>) => {
    setName(preset.name);
    setSelectedRequired(preset.requiredSubjects);
    setSelectedOptional(preset.optionalSubjects || []);
    setPriority(preset.priority || 10);
  };

  // 조합 추가/수정
  const handleSave = () => {
    if (selectedRequired.length === 0) return;

    // 이름이 비어있으면 자동 생성 이름 사용
    const finalName = name.trim() || autoGeneratedName;

    const newCombination: SubjectCombination = {
      id: editingCombination?.id || `combo-${Date.now()}`,
      name: finalName,
      requiredSubjects: selectedRequired,
      optionalSubjects: selectedOptional.length > 0 ? selectedOptional : undefined,
      minOptionalCount: selectedOptional.length > 0 ? 1 : undefined,
      targetClassNum: targetClass || undefined,
      targetClassCount: targetClassCount || undefined,
      priority,
    };

    if (editingCombination) {
      onCombinationsChange(
        combinations.map(c => c.id === editingCombination.id ? newCombination : c)
      );
    } else {
      onCombinationsChange([...combinations, newCombination]);
    }

    setIsDialogOpen(false);
    resetForm();
  };

  // 조합 삭제
  const handleRemove = (id: string) => {
    onCombinationsChange(combinations.filter(c => c.id !== id));
  };

  // 조합 편집
  const handleEdit = (combination: SubjectCombination) => {
    setEditingCombination(combination);
    setName(combination.name);
    setSelectedRequired(combination.requiredSubjects);
    setSelectedOptional(combination.optionalSubjects || []);
    setTargetClass(combination.targetClassNum || null);
    setTargetClassCount(combination.targetClassCount || null);
    setPriority(combination.priority || 10);
    setIsDialogOpen(true);
  };

  // 과목 토글
  const toggleSubject = (subject: string, type: 'required' | 'optional') => {
    if (type === 'required') {
      if (selectedRequired.includes(subject)) {
        setSelectedRequired(selectedRequired.filter(s => s !== subject));
      } else {
        setSelectedRequired([...selectedRequired, subject]);
        // 필수에 추가하면 선택에서 제거
        setSelectedOptional(selectedOptional.filter(s => s !== subject));
      }
    } else {
      if (selectedOptional.includes(subject)) {
        setSelectedOptional(selectedOptional.filter(s => s !== subject));
      } else {
        setSelectedOptional([...selectedOptional, subject]);
        // 선택에 추가하면 필수에서 제거
        setSelectedRequired(selectedRequired.filter(s => s !== subject));
      }
    }
  };

  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between">
        <Label>과목 조합 설정</Label>
        <Dialog open={isDialogOpen} onOpenChange={(open) => {
          setIsDialogOpen(open);
          if (!open) resetForm();
        }}>
          <DialogTrigger asChild>
            <Button size="sm" variant="outline">
              <Plus className="h-4 w-4 mr-1" />
              조합 추가
            </Button>
          </DialogTrigger>
          <DialogContent className="max-w-lg">
            <DialogHeader>
              <DialogTitle>
                {editingCombination ? '과목 조합 수정' : '새 과목 조합 추가'}
              </DialogTitle>
            </DialogHeader>

            <div className="space-y-4 py-4">
              {/* 프리셋 */}
              <div className="space-y-2">
                <Label className="text-xs text-muted-foreground">빠른 선택 (프리셋)</Label>
                <div className="flex flex-wrap gap-1">
                  {COMBINATION_PRESETS.map((preset) => (
                    <Button
                      key={preset.name}
                      variant="outline"
                      size="sm"
                      className="text-xs h-7"
                      onClick={() => applyPreset(preset)}
                    >
                      {getCombinationIcon(preset.name)}
                      <span className="ml-1">{preset.name}</span>
                    </Button>
                  ))}
                </div>
              </div>

              {/* 조합 이름 */}
              <div className="space-y-2">
                <Label htmlFor="combo-name">
                  조합 이름 <span className="text-xs text-muted-foreground">(비워두면 자동 생성)</span>
                </Label>
                <Input
                  id="combo-name"
                  value={name}
                  onChange={(e) => setName(e.target.value)}
                  placeholder={autoGeneratedName || '과목을 선택하면 자동 생성'}
                />
              </div>

              {/* 필수 과목 선택 */}
              <div className="space-y-2">
                <Label>
                  필수 과목 <span className="text-xs text-muted-foreground">(모두 선택해야 함)</span>
                </Label>
                <ScrollArea className="h-32 border rounded-md p-2">
                  <div className="space-y-1">
                    {availableSubjects.map((subject) => (
                      <div key={subject} className="flex items-center space-x-2">
                        <Checkbox
                          id={`req-${subject}`}
                          checked={selectedRequired.includes(subject)}
                          onCheckedChange={() => toggleSubject(subject, 'required')}
                        />
                        <label
                          htmlFor={`req-${subject}`}
                          className="text-sm cursor-pointer flex-1"
                        >
                          {subject}
                        </label>
                      </div>
                    ))}
                  </div>
                </ScrollArea>
                {selectedRequired.length > 0 && (
                  <div className="flex items-center justify-between">
                    <div className="flex flex-wrap gap-1">
                      {selectedRequired.map((s) => (
                        <Badge key={s} variant="default" className="text-xs">
                          {s}
                          <X
                            className="h-3 w-3 ml-1 cursor-pointer"
                            onClick={() => toggleSubject(s, 'required')}
                          />
                        </Badge>
                      ))}
                    </div>
                    <Badge variant="secondary" className="text-xs shrink-0 ml-2">
                      <Users className="h-3 w-3 mr-1" />
                      {previewMatchCount}명
                    </Badge>
                  </div>
                )}
              </div>

              {/* 선택 과목 (선택사항) */}
              <div className="space-y-2">
                <Label>
                  선택 과목 <span className="text-xs text-muted-foreground">(하나 이상, 선택사항)</span>
                </Label>
                <ScrollArea className="h-24 border rounded-md p-2">
                  <div className="space-y-1">
                    {availableSubjects
                      .filter(s => !selectedRequired.includes(s))
                      .map((subject) => (
                        <div key={subject} className="flex items-center space-x-2">
                          <Checkbox
                            id={`opt-${subject}`}
                            checked={selectedOptional.includes(subject)}
                            onCheckedChange={() => toggleSubject(subject, 'optional')}
                          />
                          <label
                            htmlFor={`opt-${subject}`}
                            className="text-sm cursor-pointer flex-1"
                          >
                            {subject}
                          </label>
                        </div>
                      ))}
                  </div>
                </ScrollArea>
              </div>

              {/* 배정 옵션 */}
              <div className="grid grid-cols-3 gap-3">
                <div className="space-y-2">
                  <Label>시작 반</Label>
                  <Select
                    value={targetClass?.toString() || 'auto'}
                    onValueChange={(v) => setTargetClass(v === 'auto' ? null : parseInt(v))}
                  >
                    <SelectTrigger>
                      <SelectValue placeholder="자동" />
                    </SelectTrigger>
                    <SelectContent>
                      <SelectItem value="auto">자동</SelectItem>
                      {Array.from({ length: config.classCount }, (_, i) => (
                        <SelectItem key={i + 1} value={(i + 1).toString()}>
                          {i + 1}반
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </div>
                <div className="space-y-2">
                  <Label>분산 반 수</Label>
                  <Select
                    value={targetClassCount?.toString() || 'auto'}
                    onValueChange={(v) => setTargetClassCount(v === 'auto' ? null : parseInt(v))}
                  >
                    <SelectTrigger>
                      <SelectValue placeholder="자동" />
                    </SelectTrigger>
                    <SelectContent>
                      <SelectItem value="auto">자동</SelectItem>
                      {Array.from({ length: config.classCount }, (_, i) => (
                        <SelectItem key={i + 1} value={(i + 1).toString()}>
                          {i + 1}개
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </div>
                <div className="space-y-2">
                  <Label>우선순위</Label>
                  <Select
                    value={priority.toString()}
                    onValueChange={(v) => setPriority(parseInt(v))}
                  >
                    <SelectTrigger>
                      <SelectValue />
                    </SelectTrigger>
                    <SelectContent>
                      <SelectItem value="5">낮음</SelectItem>
                      <SelectItem value="10">보통</SelectItem>
                      <SelectItem value="15">높음</SelectItem>
                      <SelectItem value="20">최우선</SelectItem>
                    </SelectContent>
                  </Select>
                </div>
              </div>
            </div>

            <DialogFooter>
              <Button variant="outline" onClick={() => setIsDialogOpen(false)}>
                취소
              </Button>
              <Button onClick={handleSave} disabled={selectedRequired.length === 0}>
                {editingCombination ? '수정' : '추가'}
              </Button>
            </DialogFooter>
          </DialogContent>
        </Dialog>
      </div>

      {/* 설정된 조합 목록 */}
      {combinations.length === 0 ? (
        <p className="text-sm text-muted-foreground text-center py-4">
          과목 조합을 추가하면 해당 조합을 선택한 학생을 우선 배정합니다.
        </p>
      ) : (
        <div className="space-y-2">
          {combinations
            .sort((a, b) => (b.priority || 0) - (a.priority || 0))
            .map((combo) => {
              const matchCount = getMatchingStudentCount(combo);

              return (
                <Card key={combo.id} className="cursor-pointer hover:bg-muted/50 transition-colors">
                  <CardContent className="p-3" onClick={() => handleEdit(combo)}>
                    <div className="flex items-center justify-between">
                      <div className="flex items-center gap-2">
                        {getCombinationIcon(combo.name)}
                        <div>
                          <div className="font-medium text-sm">{combo.name}</div>
                          <div className="text-xs text-muted-foreground flex items-center gap-1">
                            <Users className="h-3 w-3" />
                            {matchCount}명
                            {combo.targetClassCount && ` (${combo.targetClassCount}개 반)`}
                            {combo.targetClassNum && !combo.targetClassCount && ` → ${combo.targetClassNum}반`}
                          </div>
                        </div>
                      </div>
                      <Button
                        variant="ghost"
                        size="icon"
                        className="h-6 w-6"
                        onClick={(e) => {
                          e.stopPropagation();
                          handleRemove(combo.id);
                        }}
                      >
                        <X className="h-4 w-4" />
                      </Button>
                    </div>
                    <div className="mt-2 flex flex-wrap gap-1">
                      {combo.requiredSubjects.map((subject) => (
                        <Badge key={subject} variant="default" className="text-xs">
                          {subject}
                        </Badge>
                      ))}
                      {combo.optionalSubjects?.map((subject) => (
                        <Badge key={subject} variant="outline" className="text-xs">
                          {subject}
                        </Badge>
                      ))}
                    </div>
                  </CardContent>
                </Card>
              );
            })}
        </div>
      )}
    </div>
  );
};
